#!/usr/bin/env node
/**
 * Parity fixtures for the Rust QuickJS runner (src-tauri/src/pine/
 * parity_tests.rs): runs the committed engine bundle under node on the
 * engine's golden scripts (src/__tests__/pine/goldenScripts.ts) plus a few
 * trigger scripts, over the engine tests' 300 reference bars, and writes
 * what node got to src-tauri/src/pine/fixtures/parity.json. The Rust test
 * runs the same calls in QuickJS and must get the same answers.
 *
 *   npm run pine:fixtures    (after npm run pine:bundle)
 *
 * src/__tests__/pine/bundle.test.ts regenerates in memory and fails when
 * the committed file is stale.
 */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const esbuild = require("esbuild");

const ROOT = path.resolve(__dirname, "..");
const BUNDLE = path.join(ROOT, "src-tauri", "src", "pine", "engine.bundle.js");
const OUT = path.join(ROOT, "src-tauri", "src", "pine", "fixtures", "parity.json");
const TESTS = path.join(ROOT, "src", "__tests__", "pine");

/** Trigger scripts the golden set does not cover (plotchar, plotarrow, overrides). */
const EXTRA = {
  RSI_SIGNALS: `//@version=6
indicator("RSI signals")
len = input.int(14, "Length", minval = 2)
lo = input.float(30, "Oversold")
hi = input.float(70, "Overbought")
r = ta.rsi(close, len)
plot(r, "RSI")
plotshape(ta.crossover(r, lo), "Long", shape.triangleup, location.bottom)
plotchar(ta.crossunder(r, hi), "Short", "S", location.top)
plotarrow(r > hi ? 1 : r < lo ? -1 : na, "Zone")
alertcondition(ta.crossover(r, lo), "RSI long")
alertcondition(ta.crossunder(r, hi), "RSI short")
`,
  MACD_ALERT: `//@version=5
indicator("MACD alert")
[m, s, h] = ta.macd(close, 12, 26, 9)
plot(h, "Hist", style = plot.style_columns)
plotshape(ta.cross(m, s), "Cross", location = location.absolute)
alertcondition(ta.crossover(m, s), "MACD up", "up")
alertcondition(ta.crossunder(m, s), "MACD down", "down")
`,
  ERR_STRATEGY: `//@version=6
strategy("s")
strategy.entry("L", strategy.long)
`,
  ERR_LOOP_CAP: `//@version=6
indicator("loop cap")
s = 0
for i = 0 to 20000
    s += 1
plot(s)
`,
};

/** Input overrides per script (by input id), to run the override path too. */
const OVERRIDES = { RSI_SIGNALS: { 0: 7, 1: 35 }, EMA_CROSS: { 0: 5 } };

function goldenScripts() {
  const r = esbuild.buildSync({ entryPoints: [path.join(TESTS, "goldenScripts.ts")], bundle: true, format: "cjs", write: false, platform: "neutral" });
  const mod = { exports: {} };
  vm.runInNewContext(r.outputFiles[0].text, { module: mod, exports: mod.exports });
  return { ...mod.exports, ...EXTRA };
}

function loadHost() {
  const ctx = vm.createContext({});
  vm.runInContext(fs.readFileSync(BUNDLE, "utf8"), ctx);
  return ctx.PineHost;
}

function bars() {
  const ref = JSON.parse(fs.readFileSync(path.join(TESTS, "fixtures", "reference.json"), "utf8"));
  return ref.bars.map(([t, o, h, l, c, v]) => ({ t, o, h, l, c, v }));
}

/** Prefix lengths to run: the full set, every firing bar (up to 6) and two quiet ones. */
function prefixes(outputs, n) {
  const firing = new Set();
  for (const o of outputs) {
    if (o.fired) o.fired.forEach((i) => firing.add(i + 1));
    else if (o.kind !== "plot") o.values.forEach((v, i) => v !== null && v !== 0 && firing.add(i + 1));
  }
  const picked = [...firing].sort((a, b) => a - b).filter((_, i, a) => i % Math.max(1, Math.ceil(a.length / 6)) === 0);
  return [...new Set([1, 37, ...picked, n])].sort((a, b) => a - b);
}

function buildFixtures() {
  const host = loadHost();
  const all = bars();
  const scripts = goldenScripts();
  const cases = Object.keys(scripts).sort().map((name) => {
    const source = scripts[name];
    const inputs = OVERRIDES[name] ?? {};
    const args = (n) => JSON.stringify({ source, bars: all.slice(0, n), inputs, symbol: "BTCUSDT", intervalMs: 3_600_000, wallMs: 3_000 });
    const outputs = JSON.parse(host.outputs(args(all.length)));
    const runs = (outputs.ok ? prefixes(outputs.outputs, all.length) : [all.length]).map((n) => ({ n, reply: JSON.parse(host.run(args(n))) }));
    return { name, source, inputs, compile: JSON.parse(host.compile(source)), outputs, runs };
  });
  return JSON.stringify({ note: "Generated by scripts/pine-fixtures.cjs. Do not edit.", bars: all, cases }) + "\n";
}

module.exports = { buildFixtures, OUT };

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const text = buildFixtures();
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(text.length / 1024).toFixed(1)} KiB)`);
}
