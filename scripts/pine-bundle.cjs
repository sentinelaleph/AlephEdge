#!/usr/bin/env node
/**
 * Bundles the Pine-lite engine copy + pine-engine/host.ts into one IIFE for
 * the Rust QuickJS runner: src-tauri/src/pine/engine.bundle.js (committed,
 * loaded with include_str!). `npm run pine:bundle` writes it;
 * src/__tests__/pine/bundle.test.ts rebuilds in memory and fails when the
 * committed file is stale.
 *
 * Target ES2020 keeps the output inside what QuickJS parses. The "@/lib/..."
 * imports resolve through pine-engine/tsconfig.json's paths.
 */
const path = require("node:path");
const fs = require("node:fs");
const esbuild = require("esbuild");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "src-tauri", "src", "pine", "engine.bundle.js");

const OPTIONS = {
  entryPoints: [path.join(ROOT, "pine-engine", "host.ts")],
  tsconfig: path.join(ROOT, "pine-engine", "tsconfig.json"),
  absWorkingDir: ROOT,
  bundle: true,
  format: "iife",
  platform: "neutral",
  target: "es2020",
  minify: true,
  legalComments: "none",
  charset: "ascii",
  banner: { js: "/* Generated by scripts/pine-bundle.cjs from pine-engine/ (SOURCE.md). Do not edit. */" },
  write: false,
  logLevel: "silent",
};

/** The bundle text, LF line endings. */
async function buildBundle() {
  const r = await esbuild.build(OPTIONS);
  return r.outputFiles[0].text.replace(/\r\n/g, "\n");
}

async function main() {
  const text = await buildBundle();
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(text.length / 1024).toFixed(1)} KiB)`);
}

module.exports = { buildBundle, OUT };

if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exitCode = 1;
  });
}
